"""Telegram-бот ДЕЛО: «Радар заказов» и личные уведомления.

Как устроено
------------
Бот — отдельный процесс из образа backend (как worker и beat):

    python -m app.telegram.bot

Он работает с той же базой, что и сайт, и делает две вещи:

1. Принимает сообщения (long polling getUpdates): команды, кнопки фильтров
   радара, привязку аккаунта по ссылке t.me/<бот>?start=link_<токен>.
2. Раз в несколько секунд разносит новое (bot.deliver):
   - уведомления сайта (таблица notifications) — тем, кто привязал аккаунт;
   - новые открытые задания — подписчикам радара по их фильтрам.
   Что уже отправлено, записано в telegram_deliveries, поэтому после
   перезапуска бот продолжает с того же места и ничего не шлёт дважды.

Коду сайта знать о боте не нужно: уведомление, записанное в notifications
любым модулем, само придёт в Telegram.

Модули: client — вызовы Bot API, core — данные и тексты, bot — обработка
сообщений и рассылка, health — проверка живости для Docker.
"""
