/**
 * Русские названия категорий заданий.
 *
 * Ключи — значения TaskCategory из backend/app/models/__init__.py (design,
 * development, ...). Формулировки совпадают с теми, что видит пользователь в
 * каталоге (TasksPage / HomePage / CreateTaskPage), чтобы одна и та же
 * категория читалась одинаково во всём продукте.
 *
 * Зачем отдельный модуль. До этого словарь был только внутри TaskMap.jsx и в
 * коротком варианте («Дизайн» вместо «Дизайн и графика»), а админ-панель
 * рисовала сырые значения enum — в русском интерфейсе появлялись «Design»,
 * «Development», «Writing». Импортировать словарь из TaskMap нельзя: это
 * компонент карты, и админ-страница потянула бы за ним загрузку Яндекс.Карт.
 */
export const TASK_CATEGORY_LABELS = {
    development: 'Разработка сайтов и IT',
    design: 'Дизайн и графика',
    writing: 'Тексты и переводы',
    repairs: 'Ремонт и строительство',
    cleaning: 'Уборка и клининг',
    delivery: 'Курьеры и доставка',
    photo_video: 'Фото и видео',
    tutoring: 'Репетиторы',
    beauty: 'Красота',
    events: 'Мероприятия',
    business: 'Бизнес-услуги',
    other: 'Другое',
};

/**
 * Подпись категории. Для неизвестного ключа возвращает его же, но с
 * подчёркиваниями вместо пробелов — раньше в диаграмме стоял replace('_', ' ')
 * со строкой, а он меняет только первое подчёркивание, так что ключ вида
 * photo_video_extra превратился бы в «photo video_extra».
 */
export const taskCategoryLabel = (key) =>
    TASK_CATEGORY_LABELS[key] || String(key).replace(/_/g, ' ');
