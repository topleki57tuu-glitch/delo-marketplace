export const INFRA = {
  // Хостинг-провайдер: «ООО «…»».
  hostingProvider: '',
  // Страна, где стоят серверы с базой данных.
  hostingCountry: '',
  // Почтовый сервис, через который уходят письма (SMTP_HOST на сервере).
  emailProvider: '',
};

/** ИП или организация — по длине ИНН. Пустой ИНН считаем организацией. */
export function isSoleTrader() {
  return COMPANY.inn.replace(/\D/g, '').length === 12;
}

/** Подпись регистрационного номера: ОГРНИП у ИП, ОГРН у организации. */
export function registrationLabel() {
  return isSoleTrader() ? 'ОГРНИП' : 'ОГРН';
}

/** Хватает ли реквизитов, чтобы показать строку оператора в подвале. */
export function hasRequisites() {
  return Boolean(COMPANY.legalName && COMPANY.inn);
}

export function dataStoredInRussia() {
  return /^российская федерация$|^россия$|^рф$/i.test(INFRA.hostingCountry.trim());
}
